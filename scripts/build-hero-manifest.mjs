// Writes the static hero frame manifest (frame index -> filename) that the
// hero loader reads. Frames live on Cloudflare R2 under
//   website/desktop-assets/<file>  and  website/mobile-assets/<file>
// with identical filenames per cut, so the list is a plain 1-based sequence:
//   ezgif-frame-001.webp ... ezgif-frame-152.webp
//
// Re-run after re-uploading / changing the frame count:
//
//   node scripts/build-hero-manifest.mjs [count]
//
// Optionally verifies each URL resolves on R2:
//
//   node scripts/build-hero-manifest.mjs --verify

import { writeFileSync } from 'node:fs';

const R2_BASE = 'https://assets.wenilo.com/website';
const COUNT = Number(process.argv.find((a) => /^\d+$/.test(a)) ?? 152);
const VERIFY = process.argv.includes('--verify');

const frameName = (n) => `ezgif-frame-${String(n).padStart(3, '0')}.webp`;

const names = Array.from({ length: COUNT }, (_, i) => frameName(i + 1));
const manifest = { desktop: names, mobile: names.slice() };

// Optional live check: HEAD every frame in both R2 folders.
async function verify() {
  for (const device of ['desktop', 'mobile']) {
    let missing = 0;
    for (const name of manifest[device]) {
      const url = `${R2_BASE}/${device}-assets/${name}`;
      const res = await fetch(url, { method: 'HEAD' });
      if (!res.ok) {
        missing++;
        console.warn(`  ! ${res.status} ${url}`);
      }
    }
    console.log(`${device}: ${manifest[device].length - missing}/${manifest[device].length} frames reachable`);
  }
}

if (VERIFY) await verify();

const file = new URL('../src/data/heroManifest.js', import.meta.url);
const body =
  '// AUTO-GENERATED by scripts/build-hero-manifest.mjs — do not edit by hand.\n' +
  '// Hero frame filenames on Cloudflare R2, 1-based order. Same list for both\n' +
  '// device cuts; the desktop/mobile split is the R2 folder, not the filename.\n' +
  '// Regenerate: node scripts/build-hero-manifest.mjs\n\n' +
  `export const HERO_FRAMES = ${JSON.stringify(manifest, null, 2)};\n`;

writeFileSync(file, body);
console.log(`Wrote ${file.pathname} (${COUNT} frames x2)`);
