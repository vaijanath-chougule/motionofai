// Enumerates the Cloudinary hero frames via the Admin API and writes a
// static manifest (frame index -> exact public_id) that the hero loader
// reads. Cloudinary stores each frame with a random unique suffix
// (ezgif-frame-001_irwj3o), so there is NO derivable URL formula — the
// public_ids must be listed once and pinned. Re-run this whenever the
// hero frames are re-uploaded:
//
//   node scripts/build-hero-manifest.mjs
//
// Requires .env: VITE_CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY,
// CLOUDINARY_API_SECRET (loaded by the npm script via `set -a; . ./.env`).

import { writeFileSync } from 'node:fs';

const cloud = process.env.VITE_CLOUDINARY_CLOUD_NAME;
const key = process.env.CLOUDINARY_API_KEY;
const secret = process.env.CLOUDINARY_API_SECRET;

if (!cloud || !key || !secret) {
  console.error('Missing VITE_CLOUDINARY_CLOUD_NAME / CLOUDINARY_API_KEY / CLOUDINARY_API_SECRET');
  process.exit(1);
}

const auth = 'Basic ' + Buffer.from(`${key}:${secret}`).toString('base64');
const EXPECTED = 152;

const FOLDERS = {
  desktop: 'MotionOfAI/Hero/Desktop',
  mobile: 'MotionOfAI/Hero/Mobile',
};

// Pull every resource in a dynamic asset folder, following pagination.
async function listFolder(folder) {
  const out = [];
  let cursor = '';
  do {
    const url =
      `https://api.cloudinary.com/v1_1/${cloud}/resources/by_asset_folder` +
      `?asset_folder=${encodeURIComponent(folder)}&max_results=500` +
      (cursor ? `&next_cursor=${cursor}` : '');
    const res = await fetch(url, { headers: { Authorization: auth } });
    const json = await res.json();
    if (json.error) throw new Error(`${folder}: ${json.error.message}`);
    out.push(...(json.resources || []));
    cursor = json.next_cursor || '';
  } while (cursor);
  return out;
}

// public_id looks like "ezgif-frame-017_ab12cd" -> frame number 17.
const frameNo = (publicId) => {
  const m = publicId.match(/frame-(\d+)/i);
  return m ? parseInt(m[1], 10) : NaN;
};

async function build() {
  const manifest = {};
  for (const [device, folder] of Object.entries(FOLDERS)) {
    const resources = await listFolder(folder);
    // Sort ascending by frame number, then map index -> public_id.
    const sorted = resources
      .map((r) => ({ n: frameNo(r.public_id), id: r.public_id }))
      .filter((r) => !Number.isNaN(r.n))
      .sort((a, b) => a.n - b.n);

    const ids = sorted.map((r) => r.id);
    // Sanity: contiguous 1..EXPECTED, no gaps/dupes.
    const nums = sorted.map((r) => r.n);
    const missing = [];
    for (let i = 1; i <= EXPECTED; i++) if (!nums.includes(i)) missing.push(i);

    console.log(`${device}: ${ids.length} frames (expected ${EXPECTED})`);
    if (ids.length !== EXPECTED) console.warn(`  ! count mismatch`);
    if (missing.length) console.warn(`  ! missing frame numbers: ${missing.join(', ')}`);

    manifest[device] = ids;
  }

  const file = new URL('../src/data/heroManifest.js', import.meta.url);
  const body =
    '// AUTO-GENERATED by scripts/build-hero-manifest.mjs — do not edit by hand.\n' +
    '// Exact Cloudinary public_ids for the hero frame sequence, 1-based order.\n' +
    '// Regenerate after re-uploading frames: node scripts/build-hero-manifest.mjs\n\n' +
    `export const HERO_FRAMES = ${JSON.stringify(manifest, null, 2)};\n`;
  writeFileSync(file, body);
  console.log(`\nWrote ${file.pathname}`);
}

build().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
